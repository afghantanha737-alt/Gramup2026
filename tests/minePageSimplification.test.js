'use strict';
const assert = require('assert');
const fs = require('fs');
const app = fs.readFileSync(require.resolve('../public/js/app.js'), 'utf8');
const html = fs.readFileSync(require.resolve('../public/index.html'), 'utf8');

const panelStart = app.indexOf('function renderMiningPanel()');
const panelEnd = app.indexOf('\nfunction startMiningTicker()', panelStart);
assert.ok(panelStart >= 0 && panelEnd > panelStart, 'dedicated Mining panel renderer must exist');
const panel = app.slice(panelStart, panelEnd);
assert.match(panel, /class="mineConsole"/);
assert.match(panel, /class="mineSessionCard"/);
assert.match(panel, /class="mineMetrics"/);
assert.match(panel, /class="mineProgressTrack"/);
assert.match(panel, /data-mine-earned/);
assert.match(panel, /mining_start_btn/);
assert.match(panel, /mining_claim_btn/);
assert.match(panel, /mining_rigs_title/);
assert.match(panel, /mining_history_title/);
assert.match(panel, /\.map\(rig =>/);
assert.match(panel, /is-current/);
assert.match(panel, /is-locked/);
assert.match(html, /data-tab="mine"/);
assert.match(app, /async function renderMiningTab\(\)/);
assert.match(app, /async function loadMiningStatus\(/);
assert.match(app, /function miningLiveValues\(\)/);
assert.match(app, /function startMiningTicker\(\)/);
assert.match(app, /function claimMining\(\)/);
assert.match(app, /function upgradeMining\(/);
assert.match(app, /Idempotency-Key/);
assert.doesNotMatch(`${app}\n${html}`, /Lucky Spin|luckySpinPage|spinWheel|data-tab=["']spin/i);
console.log('PASS — Mine has its own live console, progressive counters, all miner tiers, history, and guarded actions');
