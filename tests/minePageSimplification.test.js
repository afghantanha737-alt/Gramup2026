'use strict';
const assert = require('assert');
const fs = require('fs');
const app = fs.readFileSync(require.resolve('../public/js/app.js'), 'utf8');
const start = app.indexOf('function renderProfileVip');
const end = app.indexOf('\nfunction retryVipPlans()', start);
assert.ok(start >= 0 && end > start, 'Mine renderer must exist');
const renderer = app.slice(start, end);
assert.match(renderer, /class="minePage"/);
assert.match(renderer, /renderMiningPanel\(\)/);
assert.match(app, /class="mineConsole"/);
assert.match(app, /class="mineSessionCard"/);
assert.doesNotMatch(renderer, /<section class="vipCatalog"/);
assert.doesNotMatch(renderer, /stars_shop_title/);
assert.match(app, /function claimMining\(\)/);
assert.match(app, /function upgradeMining\(/);
console.log('PASS — Mine page uses the live Gramup console, preserves mining actions, and omits the legacy package store');
