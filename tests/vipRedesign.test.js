'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const app = fs.readFileSync(path.join(root, 'public/js/app.js'), 'utf8');
const css = fs.readFileSync(path.join(root, 'public/css/style.css'), 'utf8');
const themeCss = fs.readFileSync(path.join(root, 'public/css/theme-selector.css'), 'utf8');
const html = fs.readFileSync(path.join(root, 'public/index.html'), 'utf8');
const miningRoute = fs.readFileSync(path.join(root, 'routes/mining.js'), 'utf8');

const panelStart = app.indexOf('function renderMiningPanel()');
const panelEnd = app.indexOf('\nfunction startMiningTicker()', panelStart);
assert.ok(panelStart >= 0 && panelEnd > panelStart, 'dedicated Mining panel renderer must exist');
const minePanel = app.slice(panelStart, panelEnd);
assert.match(minePanel, /class="mineConsole"/);
assert.match(minePanel, /data-mine-earned/);
assert.match(minePanel, /data-mine-progress/);
assert.match(minePanel, /data-mine-countdown/);
assert.match(minePanel, /class="mineMetrics"/);
assert.match(minePanel, /class="mineSessionCard"/);
assert.doesNotMatch(minePanel, /vipCatalog|vipPlanCard/);
assert.match(app, /async function renderMiningTab\(\)/);
assert.match(app, /function miningLiveValues\(\)/);
assert.match(app, /accumulatedPointsExact/);
assert.match(app, /boostRemainingSeconds/);
assert.match(app, /function claimMining\(\)/);
assert.match(app, /async function renderVipTab\(\)/);
assert.match(app, /vipCatalog/);
assert.match(miningRoute, /router\.get\('\/status'/);
assert.match(miningRoute, /router\.post\('\/claim'/);
assert.match(css, /\.mineConsole/);
assert.match(css, /\.mineProgressTrack/);
assert.match(css, /\.mineSessionCard/);
assert.match(themeCss, /html\[data-theme="silver"\] \.mineConsole/);
assert.match(html, /data-tab="mine"/);
assert.doesNotMatch(`${app}\n${html}`, /Lucky Spin|luckySpinPage|spinWheel|data-tab=["']spin/i);
console.log('PASS — Mine is a separate live console, VIP remains available, Silver styles Mine, and Lucky Spin is still absent');
