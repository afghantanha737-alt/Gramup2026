'use strict';
const assert = require('assert');
const fs = require('fs');
const pointsRoute = require('../routes/points');
const pointsSource = fs.readFileSync(require.resolve('../routes/points'), 'utf8');
const appSource = fs.readFileSync(require.resolve('../public/js/app.js'), 'utf8');
const adminSource = fs.readFileSync(require.resolve('../routes/admin'), 'utf8');
const settingsSource = fs.readFileSync(require.resolve('../models/Settings'), 'utf8');
assert.equal(pointsRoute.spinPolicy({ luckySpinEnabled: true, luckySpinRequiredStreak: 7, luckySpinCooldownHours: 24 }).requiredStreak, 7);
assert.equal(pointsRoute.spinPolicy({ luckySpinEnabled: true, luckySpinRequiredStreak: 3 }).requiredStreak, 7);
assert.equal(pointsRoute.spinPolicy({ luckySpinEnabled: false }).enabled, false);
assert.equal(pointsRoute.pickWeightedPrize(pointsRoute.SPIN_PRIZES, 0).id, 'hashrate_boost_10_1h');
assert.equal(pointsRoute.pickWeightedPrize(pointsRoute.SPIN_PRIZES, 35).id, 'up_50');
assert.equal(pointsRoute.spinPolicy({ luckySpinPrizes: [{ id: 'bad', kind: 'points', amount: 1, probability: 10 }] }).prizes.length, 6);
assert.match(pointsSource, /SPIN_STREAK_REQUIRED/);
assert.match(pointsSource, /spin\.requiredStreak/);
assert.match(pointsSource, /spin\.prizes/);
assert.match(pointsSource, /spinPrizes: spin\.prizes/);
assert.match(appSource, /renderLuckySpinBanner/);
assert.match(appSource, /openLuckySpin/);
assert.match(appSource, /spin_spin_button/);
assert.match(appSource, /function spinEligible\(\)/);
assert.match(appSource, /if \(!spinEligible\(\)\)/);
assert.match(appSource, /const canOpen = state\.spinEnabled/);
assert.match(appSource, /state\.spinPrizes/);
assert.match(appSource, /function spinSliceText\(prize, index\)/);
assert.match(appSource, /escapeHTML\(top\)/);
assert.match(appSource, /className = 'luckySpinScreen'/);
assert.match(appSource, /class="luckySpinPage"/);
assert.match(appSource, /class="luckySpinClose"/);
const homeSource = appSource.slice(appSource.indexOf('function renderHome()'), appSource.indexOf('function renderTasks()'));
assert.match(homeSource, /renderLuckySpinBanner/);
assert.doesNotMatch(homeSource, /renderLuckySpin\(\)/);
assert.match(settingsSource, /luckySpinRequiredStreak/);
assert.match(adminSource, /INVALID_LUCKY_SPIN_PRIZES/);
assert.match(adminSource, /probabilities total exactly 100/);
console.log('PASS — Lucky Spin is gated by the 7-day streak and managed from admin settings');
