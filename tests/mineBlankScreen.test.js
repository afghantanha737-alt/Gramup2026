'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const app = fs.readFileSync(path.join(root, 'public/js/app.js'), 'utf8');
const css = fs.readFileSync(path.join(root, 'public/css/style.css'), 'utf8');
const i18n = fs.readFileSync(path.join(root, 'public/js/i18n.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'public/index.html'), 'utf8');

const hubStart = app.indexOf('function renderVipMiningConsole()');
const hubEnd = app.indexOf('\nfunction renderProfileVip()', hubStart);
assert.ok(hubStart >= 0 && hubEnd > hubStart, 'VIP mining console renderer exists');
const hub = app.slice(hubStart, hubEnd);
assert.match(hub, /vipMiningLoading \? t\("vip_mining_loading"\)/);
assert.match(hub, /vip_mining_error/);
assert.match(hub, /retryVipMiningStatus\(\)/);
assert.match(hub, /data-vip-mining-earned/);
assert.match(hub, /data-vip-mining-second/);
assert.match(hub, /data-vip-miner-days/);
assert.match(hub, /data-vip-miner-percent/);
assert.match(hub, /data-vip-miner-progress/);
assert.match(app, /function vipMinerRemainingValues\(/);
assert.match(app, /vip_mining_remaining_accessible/);
assert.match(app, /setInterval\(tickVipMiningConsole, 1000\)/);
assert.match(app, /loadVipMiningStatus\(\{ force: true \}\)/);
assert.match(app, /async function retryVipMiningStatus\(\)/);
assert.match(app, /async function renderVipTab\(\)/);
assert.match(app, /loadVipPlans\(\) : Promise\.resolve\(true\),[\s\S]*loadVipMiningStatus\(\)/);
const page = app.slice(app.indexOf('function renderProfileVip()'), app.indexOf('\nfunction retryVipPlans()', app.indexOf('function renderProfileVip()')));
assert.ok(page.indexOf('${renderVipMiningConsole()}') >= 0, 'VIP page embeds live console');
assert.ok(page.indexOf('${renderVipMiningConsole()}') < page.indexOf('${vipCatalogMarkup}'), 'packages follow the mining console');
assert.match(css, /\.vipMiningConsole\s*\{/);
assert.match(css, /\.vipMiningClaim\s*\{/);
assert.match(css, /\.vipMiningProgressTrack\s*\{/);
assert.match(css, /\.vipMiningProgressFill\s*\{/);
assert.match(i18n, /vip_mining_claim:/g);
assert.equal((i18n.match(/vip_mining_remaining_percent:/g) || []).length, 3, 'remaining percentage is translated in all supported locales');
assert.equal((i18n.match(/vip_hub_title:/g) || []).length, 3, 'VIP hub title exists in all three supported locales');
assert.doesNotMatch(html, /data-tab="mine"/);
assert.match(html, /style\.css\?v=up_v36_vip_signature_20261107/);
assert.match(html, /theme-selector\.css\?v=up_v36_vip_signature_20261107/);
assert.match(html, /i18n\.js\?v=up_v35_vip_miner_progress_20261107/);
assert.match(html, /app\.js\?v=up_v37_vip_signature_20261107/);
console.log('PASS — VIP mining data loads with visible retry state, ticks every second, and localized cache-busted assets');
