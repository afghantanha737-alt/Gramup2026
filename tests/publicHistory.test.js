'use strict';

const assert = require('assert');
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const pointsRoute = fs.readFileSync(path.join(root, 'routes/points.js'), 'utf8');
const proofPage = fs.readFileSync(path.join(root, 'public/proof.html'), 'utf8');
const appJs = fs.readFileSync(path.join(root, 'public/js/app.js'), 'utf8');
const styleCss = fs.readFileSync(path.join(root, 'public/css/style.css'), 'utf8');

const routeStart = pointsRoute.indexOf("router.get('/public-history'");
assert.notStrictEqual(routeStart, -1, 'public history route exists');
const routeEnd = pointsRoute.indexOf('\n});', routeStart);
const publicHistoryRoute = pointsRoute.slice(routeStart, routeEnd);

assert.match(publicHistoryRoute, /Withdrawal\.find\(\{ status: 'paid' \}\)/);
assert.doesNotMatch(publicHistoryRoute, /\.limit\(\s*5\s*\)/, 'public payout history must not be capped to five records');
assert.match(publicHistoryRoute, /\.populate\('user', 'firstName username'\)/, 'public payout cards use limited user fields');
assert.match(publicHistoryRoute, /maskPublicPayoutName/);
assert.match(publicHistoryRoute, /Withdrawal\.aggregate\(/, 'all-time totals are calculated by MongoDB');
assert.match(publicHistoryRoute, /total: \{ \$sum: \{ \$ifNull: \['\$cryptoAmount', 0\] \} \}/);
assert.match(publicHistoryRoute, /totalByToken/);
assert.match(proofPage, /data\.totalByToken/);
assert.match(proofPage, /history\.map\(item =>/);
assert.match(proofPage, /All verified payments/);
assert.match(proofPage, /proofUser/);
assert.match(proofPage, /formatExactDate/);
assert.match(proofPage, /gramup-logo-cube-transparent\.png/);
assert.match(appJs, /payoutBoardCta/);
assert.match(appJs, /payoutBoardActions/);
assert.match(appJs, /payoutBoardMegaphone/);
assert.match(appJs, /publicHistory\.slice\(0, 5\)\.map\(item =>/);
assert.match(appJs, /wallet_public_history_board_desc/);
assert.match(proofPage, /All verified payments/);
assert.doesNotMatch(appJs, /payoutBoardCtaFrame/);
assert.match(styleCss, /\.payoutBoardCta\s*\{/);
assert.match(styleCss, /linear-gradient\(135deg, #a2f7ff/);
assert.match(styleCss, /\.payoutBoardList \.publicTxCard/);
assert.match(styleCss, /\.publicTxCard, \.proofCard \{[\s\S]*display: flex;[\s\S]*direction: rtl;[\s\S]*justify-content: space-between;/);
assert.match(styleCss, /\.publicTxPayment, \.proofPayment/);
assert.match(appJs, /class="publicTxPayment"/);
assert.match(proofPage, /class="proofPayment"/);
assert.match(appJs, /history_time_hours_ago: "\{n\} ساعت پیش"/);
assert.match(appJs, /class="publicTxFlow"[\s\S]*history_received/);
assert.match(appJs, /transaction_status_on_chain/);
assert.match(appJs, /WALLET_HISTORY_FALLBACKS[\s\S]*transaction_status_on_chain/);
assert.match(appJs, /walletHistoryText\("history_received"\)/);
assert.match(appJs, /walletHistoryText\("transaction_status_on_chain"\)/);
assert.match(appJs, /transactionTimeLabel\(item\.date\)[\s\S]*?publicTxStatus/);
assert.doesNotMatch(appJs, /publicTxDate[\s\S]*?publicTxSeparator/);
assert.match(appJs, /transaction_status_on_chain: "تایید شده روی بلاکچین"/);
assert.match(proofPage, /class="publicTxFlow"[\s\S]*receivedPayout/);
assert.doesNotMatch(styleCss, /payoutBoardCtaFrame|border: 5px solid #ff4052/);
assert.match(styleCss, /\.publicTxCard \{[\s\S]*display: grid;[\s\S]*grid-template-columns: minmax\(0, 1fr\) auto;[\s\S]*direction: rtl;/);
assert.match(styleCss, /html\[dir="ltr"\] \.publicTxIdentity/);
