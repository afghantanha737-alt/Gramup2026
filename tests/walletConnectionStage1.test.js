'use strict';
const assert = require('assert');
const fs = require('fs');

const points = fs.readFileSync('routes/points.js', 'utf8');
const user = fs.readFileSync('models/User.js', 'utf8');
const app = fs.readFileSync('public/js/app.js', 'utf8');
const wallet = fs.readFileSync('public/js/walletConnect.js', 'utf8');
const index = fs.readFileSync('public/index.html', 'utf8');
const manifest = JSON.parse(fs.readFileSync('public/tonconnect-manifest.json', 'utf8'));

assert(points.includes("router.post('/wallet/connection'"));
assert(points.includes("router.post('/wallet/connection/restore'"), 'same verified wallet can restore its server-side proof binding');
assert(points.includes("router.delete('/wallet/connection'"));
assert(points.includes("network !== '-239'"));
assert(points.includes("if (!hasRecentWalletProof(u) || u.connectedWallet?.network !== '-239')"), 'server requires a persisted verified Mainnet wallet binding for withdrawals');
assert(!points.includes('Date.now() - proofAt > 15 * 60 * 1000'), 'financial wallet authorization does not expire after 15 minutes');
assert(points.includes("if (!connectedAddress || walletAddress !== connectedAddress)"), 'withdrawals cannot target an arbitrary address when no wallet is connected');
assert(points.includes("'connectedWallet.proofVerifiedAt': null, 'connectedWallet.proofPublicKey': ''"), 'changing wallet association invalidates the previous ownership proof');
assert(points.includes('WALLET_ADDRESS_MISMATCH'));
assert(user.includes('connectedWallet:'));
assert(app.includes('window.gramupApi = api;'));
assert(app.includes('window.gramupWallet?.getAddress?.()'));
assert(wallet.includes('TonConnectUI'));
assert(wallet.includes('api/points/wallet/connection'));
assert(wallet.includes('ton-proof/verify'));
assert(wallet.includes('restorePersistedProof'), 'restored TonConnect sessions recover existing proof without reconnect');
assert(wallet.includes('proofPayloadExpiresAt'), 'one-time TON Proof payload is refreshed before it expires');
assert(wallet.includes('explicit Disconnect action below clears the persisted server binding.'), 'transient status events preserve server verification');
assert(wallet.includes("phase: 'initializing'"));
assert(wallet.includes('data-wallet-connect'));
assert(wallet.includes('data-wallet-disconnect'));
assert(wallet.includes('aria-busy='));
assert(wallet.includes('state.ui.openModal()'));
assert(wallet.includes('state.connected = false; state.proofVerified = false'));
assert(wallet.includes('onStatusChange(wallet => applyWallet(wallet), handleConnectionError)'));
assert(wallet.includes('state.proofAddress === state.address'), 'proof must match the currently connected address');
assert(wallet.includes("async function requestDeposit(amount)"));
assert(wallet.includes("async function verifyDeposit(depositId)"));
assert(wallet.includes("async function requestWithdrawal(gram, idempotencyKey)"));
assert(app.includes('window.gramupWallet.requestWithdrawal(gram, getPendingIdempotencyKey("withdraw"))'));
assert(app.includes('window.gramupWallet.requestDeposit(amount)'));
assert(app.includes('window.gramupWallet.verifyDeposit(currentDeposit._id)'));
assert(!app.includes('api("/api/points/withdraw"'), 'withdrawal HTTP request is owned by wallet integration');
assert(!app.includes('sendDepositTransaction(created.transaction)'), 'deposit transaction must not be sent twice');
assert(index.includes('@tonconnect/ui@5.0.1'));
assert(manifest.url.startsWith('https://'));
assert(manifest.iconUrl.endsWith('.png'));
console.log('ALL PASS — Phase 1 Wallet connection, address binding and manifest contract');
